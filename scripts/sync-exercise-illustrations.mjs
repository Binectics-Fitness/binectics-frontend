// Copies the exercise SVGs the Starter programs use (animated loop + still end
// pose) from the illustration library into public/exercises and regenerates
// src/lib/exercises/illustrations.ts. Withheld entries are refused.
//   node scripts/sync-exercise-illustrations.mjs <comma list of media ids> [libraryDir]
import fs from "node:fs";
import path from "node:path";

const ids = (process.argv[2] || "").split(",").map((s) => s.trim()).filter(Boolean).sort();
const lib = process.argv[3] || "/Users/daniel/Documents/binectics-plans/exercise-illustrations";
if (!ids.length) throw new Error("pass the media ids as a comma list");
const statuses = JSON.parse(fs.readFileSync(path.join(lib, "status/statuses.json"), "utf8"));
const withheld = new Set(Object.entries(statuses.overrides || {}).filter(([, v]) => v.withheld).map(([k]) => k));
const out = path.resolve("public/exercises");
fs.mkdirSync(out, { recursive: true });
for (const f of fs.readdirSync(out)) if (f.endsWith(".svg")) fs.unlinkSync(path.join(out, f));

const decode = (t) => t.replace(/&amp;/g, "&").replace(/&#39;|&apos;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">");
const rows = [];
for (const id of ids) {
  if (withheld.has(id)) throw new Error(`${id} is withheld`);
  const loop = path.join(lib, "production", `${id}.svg`);
  const still = path.join(lib, "production", `${id}-end.svg`);
  if (!fs.existsSync(loop) || !fs.existsSync(still)) { console.warn(`no asset for ${id}`); continue; }
  fs.copyFileSync(loop, path.join(out, `${id}.svg`));
  fs.copyFileSync(still, path.join(out, `${id}-end.svg`));
  const s = fs.readFileSync(loop, "utf8");
  const title = (s.match(/<title[^>]*>([^<]*)</) || [])[1] || id;
  const desc = (s.match(/<desc[^>]*>([^<]*)</) || [])[1] || "";
  rows.push([id, decode(desc ? `${title}. ${desc}` : title)]);
}
fs.writeFileSync(
  path.resolve("src/lib/exercises/illustrations.ts"),
  `// GENERATED by scripts/sync-exercise-illustrations.mjs. Do not edit by hand.
// Illustrated demo art; not professionally reviewed. Never describe it as approved.
// Starter media_id -> bundled SVG in /public/exercises (ids match the library 1:1).
// Ids with no entry (knee-plank, plank: their only views are withheld) have no art.
export const EXERCISE_ILLUSTRATION_LABELS: Record<string, string> = {
${rows.map(([id, l]) => `  ${JSON.stringify(id)}: ${JSON.stringify(l)},`).join("\n")}
};
`,
);
console.log(`${rows.length} assets`);
