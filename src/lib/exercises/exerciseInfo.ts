export type ExerciseDifficulty = 'Beginner' | 'Beginner to moderate' | 'Moderate';
export type ExerciseKind = 'reps' | 'timed' | 'mobility';

export interface ExerciseVariation {
  /** Name of the other movement. */
  name: string;
  /** What to do, in one or two plain sentences. */
  how: string;
  /** Library id when the variation is itself a library exercise (opens its page). */
  mediaId?: string;
}

export interface ExerciseInfo {
  mediaId: string;
  name: string;
  /** One plain sentence: what the movement is and what it is for. */
  summary: string;
  difficulty: ExerciseDifficulty;
  kind: ExerciseKind;
  /** Empty array means no equipment. */
  equipment: string[];
  primaryMuscles: string[];
  secondaryMuscles: string[];
  /** Numbered, in order, one action each. */
  steps: string[];
  formCues: string[];
  commonMistakes: string[];
  safetyNotes: string[];
  /** A simpler version to try first or when this feels too hard. */
  easierVariation: ExerciseVariation;
  /** What to do instead when the equipment is missing; null when none is needed. */
  withoutEquipment: ExerciseVariation | null;
  /** Short tempo/breathing hint for guided mode ("2 seconds down, 2 seconds up"). */
  tempo: string;
}

